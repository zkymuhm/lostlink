"""
Uji Kelayakan Image Matching - LOSTLINK (versi Google Drive)
Model pre-trained (tanpa pelatihan) + cosine similarity + top-5.

Struktur di Google Drive:
  My Drive/LOSTLINK_uji/data/hilang/   01_tas.jpg, 02_botol.jpg, ...   (foto pertama tiap barang)
  My Drive/LOSTLINK_uji/data/temuan/   01_tas.jpg, 02_botol.jpg, ...   (foto kedua barang yang sama)
                                       x01.jpg, x02.jpg, ...           (pengecoh)
Dua digit pertama nama file = ID pasangan (hanya untuk penilaian). Pengecoh diawali huruf 'x'.

Cara pakai di Colab: tempel seluruh kode ini ke SATU sel, lalu tekan Run.
Cara pakai lokal  : letakkan folder data/ di samping file ini, lalu: python uji_kelayakan_lostlink_drive.py
"""
import os
import subprocess
import sys
import time

# ===================== PENGATURAN =====================
FOLDER_DRIVE = "/content/drive/MyDrive/LOSTLINK_uji"   # lokasi folder di Google Drive
MODEL = "resnet18"      # "resnet18" (utama) atau "mobilenet_v3" (pembanding)
TOP_K = 5
CONTOH_GAMBAR = 5       # jumlah baris pada gambar contoh hasil
# ======================================================

# ---------- 0. Lokasi kerja: Google Drive (Colab) atau folder script (lokal) ----------
try:
    from google.colab import drive, files as colab_files
    DI_COLAB = True
    drive.mount("/content/drive")
    if not os.path.isdir(FOLDER_DRIVE):
        raise SystemExit(f"Folder {FOLDER_DRIVE} tidak ada. Periksa nama folder di Google Drive.")
    os.chdir(FOLDER_DRIVE)
except ImportError:
    DI_COLAB = False
    if "__file__" in globals():
        os.chdir(os.path.dirname(os.path.abspath(__file__)))

DATA_DIR = "data"
for sub in ("hilang", "temuan"):
    if not os.path.isdir(os.path.join(DATA_DIR, sub)):
        raise SystemExit(f"Folder {os.path.abspath(os.path.join(DATA_DIR, sub))} tidak ditemukan. "
                         "Periksa nama folder (huruf kecil semua) dan pastikan tidak tersarang ganda.")

# ---------- 1. Pustaka (dukungan foto HEIC iPhone dipasang otomatis bila perlu) ----------
import matplotlib
if not DI_COLAB:
    matplotlib.use("Agg")               # lokal: simpan gambar ke file tanpa jendela
import matplotlib.pyplot as plt
import pandas as pd
import torch
from PIL import Image, ImageOps
from torchvision import models

EXT = [".jpg", ".jpeg", ".png", ".webp"]
try:
    try:
        from pillow_heif import register_heif_opener
    except ImportError:
        subprocess.run([sys.executable, "-m", "pip", "install", "-q", "pillow-heif"], check=True)
        from pillow_heif import register_heif_opener
    register_heif_opener()
    EXT += [".heic", ".heif"]
except Exception:
    print("Catatan: dukungan HEIC tidak tersedia; gunakan foto JPG/PNG.")
EXT = tuple(EXT)

# ---------- 2. Model pre-trained ----------
torch.set_grad_enabled(False)
device = torch.device("cpu")            # sengaja CPU, mendekati kondisi laptop kelompok

if MODEL == "resnet18":
    weights = models.ResNet18_Weights.DEFAULT
    net = models.resnet18(weights=weights)
    net.fc = torch.nn.Identity()        # vektor fitur 512 angka
elif MODEL == "mobilenet_v3":
    weights = models.MobileNet_V3_Large_Weights.DEFAULT
    net = models.mobilenet_v3_large(weights=weights)
    net.classifier = torch.nn.Identity()  # vektor fitur 960 angka
else:
    raise ValueError("MODEL harus 'resnet18' atau 'mobilenet_v3'")
net.eval().to(device)
preprocess = weights.transforms()       # resize, crop tengah, normalisasi ImageNet
print("Model siap:", MODEL)


# ---------- 3. Ekstraksi fitur ----------
def buka(path):
    return ImageOps.exif_transpose(Image.open(path)).convert("RGB")  # perbaiki rotasi foto HP


def daftar_foto(folder):
    return sorted(f for f in os.listdir(folder) if f.lower().endswith(EXT) and not f.startswith("."))


def ekstrak(folder):
    nama, vek, waktu = [], [], []
    for f in daftar_foto(folder):
        t0 = time.perf_counter()
        v = net(preprocess(buka(os.path.join(folder, f))).unsqueeze(0).to(device)).flatten()
        vek.append(v / v.norm())        # dinormalisasi -> perkalian titik = cosine similarity
        waktu.append(time.perf_counter() - t0)
        nama.append(f)
    if not nama:
        raise SystemExit(f"Tidak ada foto di {folder}")
    return nama, torch.stack(vek), waktu


hilang_nama, H, t_hilang = ekstrak(os.path.join(DATA_DIR, "hilang"))
temuan_nama, T, _ = ekstrak(os.path.join(DATA_DIR, "temuan"))
print(f"{len(hilang_nama)} foto hilang, {len(temuan_nama)} foto temuan, vektor {H.shape[1]} angka")


# ---------- 4. Pencocokan top-k ----------
def id_barang(f):
    return f[:2] if f[:2].isdigit() else None   # pengecoh -> None (nama hanya untuk penilaian)


S = H @ T.T                                       # matriks kemiripan [hilang x temuan]
k = min(TOP_K, len(temuan_nama))
baris = []
for i, q in enumerate(hilang_nama):
    t0 = time.perf_counter()
    skor, idx = torch.topk(S[i], k)
    t_cocok = time.perf_counter() - t0
    kandidat = [temuan_nama[j] for j in idx.tolist()]
    benar = [id_barang(c) == id_barang(q) for c in kandidat]
    peringkat = benar.index(True) + 1 if any(benar) else None
    baris.append({
        "Foto hilang": q,
        "Peringkat pasangan benar": peringkat if peringkat else f"tidak masuk top-{k}",
        "Kandidat #1": kandidat[0],
        "Skor #1 (%)": round(skor[0].item() * 100, 1),
        "Top-1": "Ya" if peringkat == 1 else "Tidak",
        f"Top-{k}": "Ya" if peringkat else "Tidak",
        "Waktu (detik)": round(t_hilang[i] + t_cocok, 3),
    })
hasil = pd.DataFrame(baris)
hasil.index = range(1, len(hasil) + 1)

# ---------- 5. Ringkasan ----------
n, m = len(hasil), len(temuan_nama)
top1 = (hasil["Top-1"] == "Ya").sum()
topk = (hasil[f"Top-{k}"] == "Ya").sum()
acak = min(1.0, k / m)                            # peluang tebak acak masuk top-k
ringkas = pd.DataFrame({
    "Ukuran": ["Model", "Jumlah kueri (foto hilang)", "Jumlah kandidat (foto temuan + pengecoh)",
               "Akurasi top-1", f"Akurasi top-{k}", f"Pembanding: peluang acak top-{k}",
               f"Target T3 (top-{k} >= 60%)", "Rata-rata waktu per foto (detik)",
               "Waktu terlama (detik)", "Target waktu (<= 5 detik)", "Perangkat"],
    "Hasil": [MODEL, n, m,
              f"{top1}/{n} ({top1 / n * 100:.1f}%)", f"{topk}/{n} ({topk / n * 100:.1f}%)",
              f"{acak * 100:.1f}%",
              "Tercapai" if topk / n >= 0.6 else "Belum tercapai",
              f"{hasil['Waktu (detik)'].mean():.3f}", f"{hasil['Waktu (detik)'].max():.3f}",
              "Tercapai" if hasil["Waktu (detik)"].max() <= 5 else "Belum tercapai",
              "Google Colab (CPU)" if DI_COLAB else "Laptop lokal (CPU)"],
})

pd.set_option("display.width", 200)
print("\n=== HASIL PER BARANG ===")
print(hasil.to_string())
print("\n=== RINGKASAN ===")
print(ringkas.to_string(index=False))
hasil.to_csv(f"hasil_uji_{MODEL}.csv", index_label="No")
ringkas.to_csv(f"ringkasan_uji_{MODEL}.csv", index=False)

# ---------- 6. Gambar contoh (hijau = benar, merah = salah) ----------
pilih = list(range(min(CONTOH_GAMBAR, n)))
fig, ax = plt.subplots(len(pilih), k + 1, figsize=(2.4 * (k + 1), 2.6 * len(pilih)), squeeze=False)
for r, i in enumerate(pilih):
    q = hilang_nama[i]
    ax[r][0].imshow(buka(os.path.join(DATA_DIR, "hilang", q)))
    ax[r][0].set_title("Hilang: " + q, fontsize=8)
    skor, idx = torch.topk(S[i], k)
    for c, (s, j) in enumerate(zip(skor.tolist(), idx.tolist()), start=1):
        f = temuan_nama[j]
        ok = id_barang(f) == id_barang(q)
        warna = "green" if ok else "red"
        ax[r][c].imshow(buka(os.path.join(DATA_DIR, "temuan", f)))
        ax[r][c].set_title(f"#{c} {f}\n{s * 100:.1f}%", fontsize=8, color=warna)
        for sp in ax[r][c].spines.values():
            sp.set_edgecolor(warna)
            sp.set_linewidth(3)
for a in ax.flat:
    a.set_xticks([])
    a.set_yticks([])
plt.tight_layout()
plt.savefig(f"contoh_hasil_{MODEL}.png", dpi=150)

out = [f"hasil_uji_{MODEL}.csv", f"ringkasan_uji_{MODEL}.csv", f"contoh_hasil_{MODEL}.png"]
print("\nTersimpan di", os.getcwd(), ":", ", ".join(out))
if DI_COLAB:
    plt.show()

